// Copies text with the modern async Clipboard API, falling back to the old
// execCommand trick for browsers/contexts (e.g. non-HTTPS dev) where
// navigator.clipboard isn't available. Returns whether it worked so callers
// can show an honest success/failure state instead of assuming it did.
export async function copyToClipboard(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text)
      return true
    } catch {
      // fall through to the legacy path
    }
  }
  try {
    const el = document.createElement('textarea')
    el.value = text
    el.style.position = 'fixed'
    el.style.opacity = '0'
    document.body.appendChild(el)
    el.focus()
    el.select()
    const ok = document.execCommand('copy')
    document.body.removeChild(el)
    return ok
  } catch {
    return false
  }
}
